package com.e1c.v8codestyle.bsl.check.itests;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertNull;

import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.function.Consumer;

import org.eclipse.xtext.nodemodel.util.NodeModelUtils;

import com._1c.g5.v8.dt.validation.marker.StandardExtraInfo;

/** Frozen oracle generated by unmodified analyser at LS 33a1400681e342ad4bd12281dcee8c7db781ee3d. */
final class MultilingualStringPinnedAssertions
{
    private MultilingualStringPinnedAssertions()
    {
    }

    static void verify(AbstractSingleModuleTestBase test, boolean template, Consumer<String> languages) throws Exception
    {
        List<String[]> oracle;
        try (var input = MultilingualStringPinnedAssertions.class
            .getResourceAsStream("/resources/localization-pinned-oracle.tsv")) //$NON-NLS-1$
        {
            assertNotNull(input);
            oracle = new String(input.readAllBytes(), StandardCharsets.UTF_8).lines().skip(1)
                .map(line -> line.split("\t", -1)).toList(); //$NON-NLS-1$
        }
        try
        {
            for (String fixture : List.of("localization-overlap", "localization-classification", //$NON-NLS-1$ //$NON-NLS-2$
                "localization-boundaries")) //$NON-NLS-1$
            {
                test.updateModule("/resources/" + fixture + ".bsl"); //$NON-NLS-1$ //$NON-NLS-2$
                var node = NodeModelUtils.getNode(test.getModule());
                for (var leaf : node.getLeafNodes())
                {
                    assertNull(fixture + ": " + leaf, leaf.getSyntaxErrorMessage()); //$NON-NLS-1$
                }
                String source = node.getRootNode().getText();
                for (String declared : List.of("ru", "ru,en", "en", " RU, en,ru,ru ", "", ",ru,,en,", ",")) //$NON-NLS-1$ //$NON-NLS-2$ //$NON-NLS-3$ //$NON-NLS-4$ //$NON-NLS-5$ //$NON-NLS-6$ //$NON-NLS-7$
                {
                    languages.accept(declared);
                    List<String> expected = new ArrayList<>();
                    for (var row : oracle)
                    {
                        if (fixture.equals(row[0]) && declared.equals(row[1])
                            && template == Boolean.parseBoolean(row[6]))
                        {
                            int start = offset(source, Integer.parseInt(row[2]), Integer.parseInt(row[3]));
                            int end = offset(source, Integer.parseInt(row[4]), Integer.parseInt(row[5]));
                            expected.add(start + ":" + (end - start) + ":" + row[7]); //$NON-NLS-1$ //$NON-NLS-2$
                        }
                    }
                    var actual = test.getModuleMarkers().stream().map(marker ->
                        marker.getExtraInfo().get(StandardExtraInfo.TEXT_OFFSET) + ":" //$NON-NLS-1$
                        + marker.getExtraInfo().get(StandardExtraInfo.TEXT_LENGTH) + ":" //$NON-NLS-1$
                        + marker.getMessage().substring(marker.getMessage().indexOf('[')))
                        .sorted().toList();
                    expected.sort(Comparator.naturalOrder());
                    assertEquals(fixture + " declared=" + declared + " template=" + template, expected, actual); //$NON-NLS-1$ //$NON-NLS-2$
                }
            }
        }
        finally
        {
            languages.accept("ru"); //$NON-NLS-1$
        }
    }

    private static int offset(String source, int line, int column)
    {
        int start = 0;
        for (int current = 1; current < line; current++)
        {
            start = source.indexOf('\n', start) + 1;
        }
        return start + column;
    }
}
